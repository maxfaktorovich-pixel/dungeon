window.addEventListener("DOMContentLoaded", () => {
  setupBrushes();
  setupInput();

  if (loadGame()) {
    say("С возвращением в подземелье!", "title");
  } else {
    newGame();
    say("Добро пожаловать в Подземелье Строителя!", "title");
    say("Ты можешь исследовать подземелье — и строить его сам.");
    say("Команды пишутся по-английски. Набери help, чтобы увидеть все.");
    say("Или нажимай кнопки внизу и рисуй на карте слева.");
  }

  describeRoom();
  renderAll();
});
